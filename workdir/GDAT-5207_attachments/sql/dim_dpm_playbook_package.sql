SELECT
CAST(WORKSPACE_ID AS BIGINT) AS workspace_id,
CAST(PLAYBOOK_ID AS STRING) AS playbook_id,
CAST(UNIQUE_PACKAGE_ID AS STRING) AS unique_package_id,
CAST(PACKAGE_ID AS INT) AS package_id,
CAST(GATE_ID AS INT) AS gate_id,
CAST(GATE_TITLE AS STRING) AS gate_title,
CAST(GATE_DESCRIPTION AS STRING) AS gate_description,
CAST(GATE_SUB_DESCRIPTION AS STRING) AS gate_sub_description,
CAST(DISCIPLINE_ID AS INT) AS discipline_id,
CAST(DISCIPLINE_TITLE AS STRING) AS discipline_title,
CAST(DISCIPLINE_DESCRIPTION AS STRING) AS discipline_description,
CAST(PACKAGE_IS_REQUIRED AS STRING) AS package_is_required,
CAST(PACKAGE_TITLE AS STRING) AS package_title,
CAST(PACKAGE_START_DATE AS TIMESTAMP) AS package_start_date,
CAST(PACKAGE_DUE_DATE AS TIMESTAMP) AS package_due_date,
CAST(PACKAGE_ASSIGNED_TO AS STRING) AS package_assigned_to,
CAST(PACKAGE_STATUS AS STRING) AS package_status,
CAST(CREATED_BY_USER AS STRING) AS created_by_user,
CAST(CREATED_BY_ORGANISATION AS STRING) AS created_by_organisation,
CAST(UNIQUE_PARENT_PACKAGE_ID AS INT) AS unique_parent_package_id,
CAST(GATE_STATUS AS STRING) AS gate_status,
CAST(PACKAGE_PROGRESS_PERCENTAGE AS INT) AS package_progress_percentage,
CAST(PACKAGE_PROGRESS_NUMBER AS INT) AS package_progress_number,
CAST(PARENT_PACKAGE_ID AS INT) AS parent_package_id,
CAST(LOAD_DATE AS TIMESTAMP) AS load_date,
CAST(curdate() AS DATE) AS snapshot_date
FROM
dpm_playbook_package
